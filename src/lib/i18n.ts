// Central translation dictionary.
const UI: Record<Language, Record<UiKey, string>> = {
  en,
  hi,
  ta,
  te,
};

// Retrieve a translated string and replace dynamic placeholders.
export function t(
  language: Language,
  key: UiKey,
  vars?: Record<string, string | number>
): string {
  const translations = UI[language] ?? en;

  let text = translations[key] ?? en[key];

  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }

  return text;
}

// Get the correct speech recognition locale for a language.
export function speechLocaleFor(language: Language): string {
  return (
    LANGUAGES.find((item) => item.code === language)?.speechLocale ??
    'en-IN'
  );
}
